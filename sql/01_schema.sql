-- ============================================================================
-- 01_schema.sql
-- JW · PROPER STA. FE CONGREGATION  |  Eskedyul sa Midweek nga Tigom
-- Isolated schema: everything lives in `midweek`. Nothing in `public`
-- (the Field Service app) is touched.
-- ============================================================================

create schema if not exists midweek;

-- ---------------------------------------------------------------------------
-- updated_at helper (lives inside midweek so it is self-contained)
-- ---------------------------------------------------------------------------
create or replace function midweek.set_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

-- Allowed scheduler pools (who is eligible for which family of parts)
--   elder         -> Chairman, Living-as-Christians parts, CBS conductor, prayers
--   ms            -> Treasures talk, Spiritual Gems, 5-min talk, CBS reader
--   bible_reading -> Bible reading student
--   female        -> Apply-Yourself student/assistant parts (also male students)

-- ---------------------------------------------------------------------------
-- part_codes : the legend. One row per (pool, code). Editable in the app.
-- ---------------------------------------------------------------------------
create table if not exists midweek.part_codes (
  id    bigint generated by default as identity primary key,
  pool  text not null check (pool in ('elder','ms','bible_reading','female')),
  code  text not null,
  label text not null,
  sort  int  not null default 0,
  needs_review boolean not null default false,
  unique (pool, code)
);

-- ---------------------------------------------------------------------------
-- members : the people. One canonical row per person.
-- ---------------------------------------------------------------------------
create table if not exists midweek.members (
  id         bigint generated by default as identity primary key,
  name       text not null unique,
  active     boolean not null default true,
  sort       int  not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create trigger members_updated before update on midweek.members
  for each row execute function midweek.set_updated_at();

-- ---------------------------------------------------------------------------
-- member_pools : which scheduler pool(s) a member belongs to, + eligibility note
--   (e.g. "ENB only", "CLP only", "PP2 only")
-- ---------------------------------------------------------------------------
create table if not exists midweek.member_pools (
  member_id bigint not null references midweek.members(id) on delete cascade,
  pool      text   not null check (pool in ('elder','ms','bible_reading','female')),
  note      text,
  primary key (member_id, pool)
);

-- ---------------------------------------------------------------------------
-- assignments : the scheduler GRID. One code per member / pool / meeting date.
--   This is the "Assign Bahin" matrix and the fairness history.
-- ---------------------------------------------------------------------------
create table if not exists midweek.assignments (
  id           bigint generated by default as identity primary key,
  member_id    bigint not null references midweek.members(id) on delete cascade,
  pool         text   not null check (pool in ('elder','ms','bible_reading','female')),
  meeting_date date   not null,
  code         text   not null,
  created_at   timestamptz not null default now(),
  unique (member_id, pool, meeting_date)
);
create index if not exists assignments_date_idx on midweek.assignments(meeting_date);
create index if not exists assignments_member_idx on midweek.assignments(member_id);

-- ---------------------------------------------------------------------------
-- meetings : the weekly program HEADER (one printable "Eskedyul" per week)
-- ---------------------------------------------------------------------------
create table if not exists midweek.meetings (
  id             bigint generated by default as identity primary key,
  meeting_date   date,                         -- the week's midweek-meeting date (nullable)
  week_label     text not null,                -- e.g. "OKTUBRE 19-25"
  reading        text,                         -- e.g. "JEREMIAS 45-46"
  is_special     boolean not null default false,
  special_text   text,                         -- e.g. "WALAY MIDWEEK NGA TIGOM ...\nSIRKITONG ASEMBLIYA ..."
  chairman       text,
  opening_prayer text,
  closing_prayer text,
  opening_song   text,
  sort           int not null default 0,
  created_at     timestamptz not null default now(),
  updated_at     timestamptz not null default now()
);
create trigger meetings_updated before update on midweek.meetings
  for each row execute function midweek.set_updated_at();

-- ---------------------------------------------------------------------------
-- meeting_parts : the ordered body of one weekly program
-- ---------------------------------------------------------------------------
create table if not exists midweek.meeting_parts (
  id             bigint generated by default as identity primary key,
  meeting_id     bigint not null references midweek.meetings(id) on delete cascade,
  pos            int not null,
  section        text,    -- INTRO | BAHANDI | MAGMAEPEKTIBO | KRISTOHANONG PAGKINABUHI | KONKLUSYON
  item_no        text,    -- "1".."10" or null
  title          text,    -- part title incl. "(10 min.)"
  setting        text,    -- "IMPORMAL NGA PAGSANGYAW" etc., or a song label
  assignee       text,    -- main person (or Estudyante)
  assignee_role  text,    -- "Tsirman" | "Estudyante" | "Tigdumala" | null
  assistant      text,    -- Assistant / Tagabasa name
  assistant_role text,    -- "Assistant" | "Tagabasa" | null
  is_song        boolean not null default false
);
create index if not exists meeting_parts_meeting_idx on midweek.meeting_parts(meeting_id, pos);

-- ---------------------------------------------------------------------------
-- app_settings : misc key/value (congregation name, PIN, etc.)
-- ---------------------------------------------------------------------------
create table if not exists midweek.app_settings (
  key   text primary key,
  value text
);

-- ---------------------------------------------------------------------------
-- Row Level Security — mirror the Field Service app: the browser uses the
-- public "anon" role, so enable RLS and grant anon full access. Data is
-- low-sensitivity congregation scheduling; the app itself gates with a PIN.
-- ---------------------------------------------------------------------------
do $$
declare t text;
begin
  for t in
    select tablename from pg_tables where schemaname = 'midweek'
  loop
    execute format('alter table midweek.%I enable row level security;', t);
    execute format('drop policy if exists %I on midweek.%I;', t||'_anon_all', t);
    execute format(
      'create policy %I on midweek.%I for all to anon using (true) with check (true);',
      t||'_anon_all', t);
  end loop;
end $$;

-- ---------------------------------------------------------------------------
-- Grants so PostgREST (anon / authenticated) can reach the midweek schema.
-- The schema must also be added to the API "Exposed schemas" — the deploy
-- script (migration/deploy.mjs) does that on the authenticator role.
-- ---------------------------------------------------------------------------
grant usage on schema midweek to anon, authenticated, service_role;
grant all on all tables    in schema midweek to anon, authenticated, service_role;
grant all on all sequences in schema midweek to anon, authenticated, service_role;
grant all on all functions in schema midweek to anon, authenticated, service_role;
alter default privileges in schema midweek
  grant all on tables to anon, authenticated, service_role;
alter default privileges in schema midweek
  grant all on sequences to anon, authenticated, service_role;
